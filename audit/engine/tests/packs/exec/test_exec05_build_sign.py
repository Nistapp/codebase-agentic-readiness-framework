"""`EXEC-05` reads a tracked file under ``build/`` as generated only with a sign of it (issue #260).

Every tracked file under ``dist/`` stays generated. Under ``build/`` a file is generated when its name carries a
generated hint or suffix, or when the target's own ignore rules match it while git tracks it (the list `SEC-01`
and `SEC-03` read). A hand-written script there keeps the kind it has elsewhere. The check runs in-process here,
so coverage traces it.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import support  # noqa: E402

from audit.rules.checks.execution import check_exec05  # noqa: E402
from audit.rules.registry import REGISTRY_BY_ID  # noqa: E402
from audit.scan import Kind, _classify, build_inventory, in_signed_generated_dir  # noqa: E402
from audit.stack import detect_stack  # noqa: E402
from audit.target import resolve_target  # noqa: E402


def _git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(root), *args], text=True, capture_output=True)


class ClassifyTests(unittest.TestCase):
    def test_a_build_folder_alone_does_not_make_a_file_generated(self):
        cases = {
            "build/release.sh": Kind.SCRIPT,
            "build/docker/app.py": Kind.SOURCE,
            "pkg/build/config.yaml": Kind.CONFIG,
            "Build/notes.md": Kind.DOC,
        }
        for rel, kind in cases.items():
            with self.subTest(rel=rel):
                self.assertIs(_classify(rel), kind)

    def test_a_generated_hint_or_suffix_under_build_is_still_generated(self):
        for rel in ("build/app.min.js", "build/app.js.map", "build/api.pb.go", "build/generated/x.ts"):
            with self.subTest(rel=rel):
                self.assertIs(_classify(rel), Kind.GENERATED)

    def test_the_signed_folder_matches_a_whole_folder_name_in_any_case(self):
        for rel in ("build/x", "a/Build/x", "a/b/BUILD/c/x"):
            with self.subTest(rel=rel):
                self.assertTrue(in_signed_generated_dir(rel))
        for rel in ("build", "prebuild/x", "builds/x", "build.py", "dist/x"):
            with self.subTest(rel=rel):
                self.assertFalse(in_signed_generated_dir(rel))


class CheckTests(unittest.TestCase):
    def outcome(self, files: dict[str, str], *, forced: tuple[str, ...] = ()):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            support.write(root, "README.md", "x\n")
            for rel, text in files.items():
                support.write(root, rel, text)
            self.assertEqual(_git(root, "init", "-q").returncode, 0)
            self.assertEqual(_git(root, "add", "-A").returncode, 0)
            for rel in forced:
                self.assertEqual(_git(root, "add", "-f", rel).returncode, 0)
            inventory = build_inventory(root)
            return check_exec05(
                spec=REGISTRY_BY_ID["EXEC-05"],
                target=resolve_target(root),
                inventory=inventory,
                stack=detect_stack(inventory),
                components=None,
                session=None,
            )

    @staticmethod
    def cited(outcome) -> list[str]:
        return [e.path for f in outcome.findings for e in f.evidence]

    def test_a_tracked_hand_written_script_in_build_passes(self):
        outcome = self.outcome({"build/release.sh": "#!/bin/sh\nnpm pack\n", "build/docker/Dockerfile": "FROM x\n"})
        self.assertEqual(outcome.verdict.value, "PASS")
        self.assertEqual(outcome.findings, [])

    def test_a_tracked_file_in_build_the_ignore_rules_match_fails(self):
        outcome = self.outcome(
            {".gitignore": "build/\n", "build/out.js": "x\n", "build/Main.class": "x\n"},
            forced=("build/out.js", "build/Main.class"),
        )
        self.assertEqual(outcome.verdict.value, "FAIL")
        self.assertEqual(self.cited(outcome), ["build/Main.class", "build/out.js"])

    def test_an_ignored_build_file_with_a_generated_header_passes(self):
        outcome = self.outcome(
            {".gitignore": "build/\n", "build/out.js": "// @generated by the bundler\n"}, forced=("build/out.js",)
        )
        self.assertEqual(outcome.verdict.value, "PASS")

    def test_a_file_the_rules_ignore_outside_build_is_not_read_as_generated(self):
        outcome = self.outcome({".gitignore": "*.log\n", "notes.log": "x\n"}, forced=("notes.log",))
        self.assertEqual(outcome.verdict.value, "PASS")

    def test_a_minified_file_in_build_fails_without_an_ignore_rule(self):
        outcome = self.outcome({"build/app.min.js": "x\n", "build/release.sh": "#!/bin/sh\n"})
        self.assertEqual(outcome.verdict.value, "FAIL")
        self.assertEqual(self.cited(outcome), ["build/app.min.js"])

    def test_every_tracked_file_in_dist_is_still_generated(self):
        outcome = self.outcome({"dist/release.sh": "#!/bin/sh\n"})
        self.assertEqual(outcome.verdict.value, "FAIL")
        self.assertEqual(self.cited(outcome), ["dist/release.sh"])

    def test_a_binary_ignored_build_file_is_left_to_the_binaries_check(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            support.write(root, ".gitignore", "build/\n")
            (root / "build").mkdir()
            (root / "build" / "Main.class").write_bytes(b"\xca\xfe\xba\xbe\x00\x00")
            self.assertEqual(_git(root, "init", "-q").returncode, 0)
            self.assertEqual(_git(root, "add", "-A").returncode, 0)
            self.assertEqual(_git(root, "add", "-f", "build/Main.class").returncode, 0)
            inventory = build_inventory(root)
            outcome = check_exec05(
                spec=REGISTRY_BY_ID["EXEC-05"],
                target=resolve_target(root),
                inventory=inventory,
                stack=detect_stack(inventory),
                components=None,
                session=None,
            )
        self.assertEqual(outcome.verdict.value, "PASS")


if __name__ == "__main__":
    unittest.main()
